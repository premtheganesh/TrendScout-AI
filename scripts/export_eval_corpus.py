"""
Freeze the current corpus as a versioned, committed evaluation snapshot.

Writes one JSON line per document for startups, articles, github_repos and
canonical_entities, minus the embeddings (they are rebuilt from the text by
build_indexes.py, and would triple the file size). `_id`s are preserved so
canonical_entities.mentioned_in.doc_id links stay valid.

Run:
    python scripts/export_eval_corpus.py                 # -> data/eval/corpus_v1.jsonl
    python scripts/export_eval_corpus.py --out data/eval/corpus_v2.jsonl
"""

import sys
import os
sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), '..')))

import argparse
from bson import json_util

from src.config import PROJECT_ROOT
from src.database.mongo_client import MongoDBClient

COLLECTIONS = ('startups', 'articles', 'github_repos', 'canonical_entities')

# Regenerated by build_indexes.py; excluded so the snapshot is small and
# independent of the embedding model.
VOLATILE_FIELDS = ('embedding', 'embedding_generated_at')

DEFAULT_OUT = os.path.join(PROJECT_ROOT, 'data', 'eval', 'corpus_v1.jsonl')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', default=DEFAULT_OUT)
    args = parser.parse_args()

    mongo = MongoDBClient()
    print(f"Exporting from database '{mongo.db_name}' -> {args.out}")

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    counts = {}
    with open(args.out, 'w', encoding='utf-8') as f:
        for collection in COLLECTIONS:
            docs = list(mongo.db[collection].find().sort('_id', 1))
            for doc in docs:
                for field in VOLATILE_FIELDS:
                    doc.pop(field, None)
                f.write(json_util.dumps({'collection': collection, 'doc': doc}) + '\n')
            counts[collection] = len(docs)

    mongo.close()
    for collection, n in counts.items():
        print(f"  {collection:<20} {n:>5}")
    print(f"  {'total':<20} {sum(counts.values()):>5}   "
          f"({os.path.getsize(args.out) / 1024:.0f} KB)")


if __name__ == '__main__':
    main()
